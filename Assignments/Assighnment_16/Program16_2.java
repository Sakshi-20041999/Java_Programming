class Program16_2
{
    void checkEvenOdd(int num)
    {
        if(num % 2 == 0)
            System.out.println(num + " is Even.");
        else
            System.out.println(num + " is Odd.");
    }
    
////////////////////////////////////////////////////////////////////
//
//  Entry point function
//
////////////////////////////////////////////////////////////////////
    public static void main(String args[])
    {
        Program16_2 obj = new Program16_2();
        obj.checkEvenOdd(7);
    }
}

